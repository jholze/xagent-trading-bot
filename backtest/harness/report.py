"""Markdown + JSON report for a harness run."""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from zoneinfo import ZoneInfo

from .scenarios import N_TRIALS, ScenarioResult

BERLIN = ZoneInfo("Europe/Berlin")


def _f(x: float | None, d: int = 2) -> str:
    if x is None:
        return "n/a"
    return f"{x:,.{d}f}"


def render(results: list[ScenarioResult], sources: dict, started: datetime) -> str:
    lines = [
        f"# Backtest harness run {started.astimezone(BERLIN):%Y-%m-%d %H:%M} (Europe/Berlin)",
        "",
        "Generated by `python -m backtest.harness`. Paper research only; no orders, no keys.",
        "",
        "## Data",
        "",
        "| Item | Value |",
        "|---|---|",
    ]
    for k, v in sources.items():
        lines.append(f"| {k} | {v} |")
    lines += [
        "",
        "## Verdicts",
        "",
        "| Scenario | Primary vs baseline | Windows won | DSR (N=%d) | Excess/day bp, 95 %% CI | PBO | Verdict |" % N_TRIALS,
        "|---|---|---|---|---|---|---|",
    ]
    for r in results:
        v = r.verdict
        lines.append(
            f"| ({r.key}) {r.title} | {r.primary} vs {r.baseline} | {v.windows_won}/{v.windows} | {_f(v.dsr)} | "
            f"{_f(r.excess_daily_mean_bp, 1)} [{_f(v.ci_low * 1e4, 1)}, {_f(v.ci_high * 1e4, 1)}] | "
            f"{_f(r.pbo)} | **{v.label}** |"
        )
    lines += [
        "",
        "Rules: GO = wins >= 2 of 3 windows, DSR > 0.5, block-bootstrap CI of daily excess return above 0 and no guardrail "
        "(share of open lots <= -20 %, max drawdown, capital in losing lots) worse. OBSERVE = wins but DSR or CI "
        "short. KILL = fewer than 2 windows or a guardrail worse.",
        "",
    ]
    for r in results:
        lines += [f"## ({r.key}) {r.title}", "", r.question, "", f"Mode: `{r.mode}`. Verdict: **{r.verdict.label}** - {r.verdict.reason}.", ""]
        lines += ["Windows: " + ", ".join(f"{w} {a[:16]} to {b[:16]} UTC" for w, a, b in r.window_labels), ""]
        lines += [
            "| Variant | Lots | Invested USDT | PnL USDT | PnL % | Max DD % | Open <= -20 % | Hit % | Avg win | Avg loss | Capital in losing lots | Stops full/partial/escalated | Partial rejects | Filtered |",
            "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|",
        ]
        for vr in r.variants:
            m = vr.full
            lines.append(
                f"| {vr.name} | {m.lots} | {_f(m.invested_usdt, 0)} | {_f(m.pnl_usdt, 0)} | {_f(m.pnl_pct)} | {_f(m.max_dd_pct)} | "
                f"{m.open_le_minus20}/{m.open_lots} ({_f(m.share_open_le_minus20, 1)} %) | {_f(m.hit_rate, 1)} | {_f(m.avg_win_usdt, 0)} | "
                f"{_f(m.avg_loss_usdt, 0)} | {_f(m.capital_in_losing_lots, 0)} | {m.stop_full}/{m.stop_partial}/{m.escalated} | "
                f"{m.partial_rejects} | {m.filtered_out} |"
            )
        lines += ["", "| Variant | " + " | ".join(f"{w} PnL % (USDT)" for w, _a, _b in r.window_labels) + " |"]
        lines += ["|---|" + "---|" * len(r.window_labels)]
        for vr in r.variants:
            cells = [f"{_f(vr.windows[w].pnl_pct)} ({_f(vr.windows[w].pnl_usdt, 0)})" for w, _a, _b in r.window_labels]
            lines.append(f"| {vr.name} | " + " | ".join(cells) + " |")
        lines += [""]
        for vr in r.variants:
            lines.append(f"- `{vr.name}`: {vr.description}")
        for n in r.notes:
            lines.append(f"- {n}")
        lines.append("")
    return "\n".join(lines) + "\n"


def write(results: list[ScenarioResult], sources: dict, started: datetime, out_dir: Path, stem: str) -> tuple[Path, Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    md = out_dir / f"{stem}.md"
    js = out_dir / f"{stem}.json"
    md.write_text(render(results, sources, started), encoding="utf-8")
    payload = {"sources": sources, "n_trials": N_TRIALS, "scenarios": [r.to_json() for r in results]}
    js.write_text(json.dumps(payload, indent=1, default=str), encoding="utf-8")
    return md, js
